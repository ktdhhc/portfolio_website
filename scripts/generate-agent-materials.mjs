import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = process.cwd();
const contentDir = join(root, 'content');
const outputDir = join(root, 'functions', 'api', '_generated');
const outputFile = join(outputDir, 'agent-materials.ts');

async function pathExists(path) {
  try {
    await readFile(path);
    return true;
  } catch {
    return false;
  }
}

async function collectMaterials() {
  const materials = {};

  materials['profile.json'] = await readFile(join(contentDir, 'profile.json'), 'utf-8');
  materials['resume.json'] = await readFile(join(contentDir, 'resume.json'), 'utf-8');
  materials['agent/system-prompt.md'] = await readFile(join(contentDir, 'agent', 'system-prompt.md'), 'utf-8');
  materials['agent/answer-rules.md'] = await readFile(join(contentDir, 'agent', 'answer-rules.md'), 'utf-8');

  const projectsDir = join(contentDir, 'projects');
  const projectNames = await readdir(projectsDir);

  for (const projectName of projectNames) {
    const projectDir = join(projectsDir, projectName);
    const indexPath = join(projectDir, 'index.md');
    if (await pathExists(indexPath)) {
      materials[`projects/${projectName}/index.md`] = await readFile(indexPath, 'utf-8');
    }

    const refsDir = join(projectDir, 'refs');
    try {
      const refNames = await readdir(refsDir);
      for (const refName of refNames) {
        if (refName.endsWith('.md')) {
          materials[`projects/${projectName}/refs/${refName}`] = await readFile(join(refsDir, refName), 'utf-8');
        }
      }
    } catch {
      // refs/ is optional per project.
    }
  }

  return materials;
}

const materials = await collectMaterials();
const readableFileIds = Object.keys(materials).filter((file) => file === 'resume.json' || file.startsWith('projects/'));
await mkdir(outputDir, { recursive: true });
await writeFile(
  outputFile,
  `// Generated by scripts/generate-agent-materials.mjs. Do not edit manually.\n` +
    `export const agentMaterials = ${JSON.stringify(materials, null, 2)} as const;\n` +
    `export const readableAgentFileIds = ${JSON.stringify(readableFileIds, null, 2)} as const;\n`,
);
